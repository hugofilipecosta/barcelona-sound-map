function store({
  id,
  name,
  neighborhood,
  address,
  distanceKm,
  websiteUrl,
  specialties,
  note = "Curated Barcelona record-store registry. Live place sources can enrich hours and metadata.",
}) {
  return {
    id,
    type: "store",
    name,
    neighborhood,
    address,
    distanceKm,
    moods: placeMoods([name, ...specialties, note], ["Vinyl digging"]),
    source: "Manual seed",
    freshness: "Seeded",
    sourceUrl: websiteUrl,
    mapUrl: mapSearchUrl(name, address),
    websiteUrl,
    hours: "Check today",
    specialties,
    note,
  };
}

function spot({
  id,
  name,
  neighborhood,
  address,
  distanceKm,
  websiteUrl,
  sourceUrl,
  specialties,
  hours,
  note,
  confidence = 88,
}) {
  return {
    id,
    type: "spot",
    name,
    neighborhood,
    address,
    distanceKm,
    moods: placeMoods(
      [name, ...specialties, hours, note],
      ["Listening bar", "Coffee", "Vinyl digging"],
    ),
    source: "Manual seed",
    freshness: "Seeded",
    sourceUrl,
    mapUrl: mapSearchUrl(name, address),
    websiteUrl,
    hours,
    specialties,
    note,
    confidence,
    confidenceLabel: confidence >= 80 ? "High confidence" : "Good signal",
  };
}

function placeMoods(values, baseMoods) {
  const text = normalizeGenreText(values.join(" "));
  const moods = [...baseMoods];

  addMoodIf(moods, "Jazz", /\b(jazz|blues|swing|jam session)\b/.test(text));
  addMoodIf(
    moods,
    "Hiphop / Funk",
    /\b(hip[ -]?hop|hiphop|rap|r&b|trap|funk|soul|groove|disco)\b/.test(text),
  );
  addMoodIf(
    moods,
    "Electronic",
    /\b(electronic|electro|techno|house|club|dj|dance|ambient|leftfield)\b/.test(text),
  );
  addMoodIf(moods, "Rock", /\b(rock|punk|metal|hardcore|psych|guitar|oldies)\b/.test(text));
  addMoodIf(moods, "Indie", /\b(indie|independent|alternative|local label|local-label)\b/.test(text));
  addMoodIf(moods, "Experimental", /\b(experimental|leftfield|avant|noise)\b/.test(text));
  addMoodIf(
    moods,
    "Global",
    /\b(world|global|latin|afro|reggae|dub|salsa|flamenc|flamenco|rumba|cumbia)\b/.test(text),
  );

  return moods;
}

function addMoodIf(moods, mood, shouldAdd) {
  if (shouldAdd && !moods.includes(mood)) moods.push(mood);
}

function normalizeGenreText(value) {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

function mapSearchUrl(name, address) {
  const place = String(address ?? "").trim();
  const query = /barcelona$/i.test(place)
    ? `${name} ${place}`
    : `${name} ${place} Barcelona`;
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(
    query,
  )}`;
}
